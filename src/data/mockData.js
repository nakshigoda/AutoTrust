// Helper: find vehicle by registration number
export function findVehicleByRegNumber(regNumber) {
  return mockVehicles.find(
    v => v.registrationNumber.toLowerCase() === regNumber.toLowerCase().replace(/\s+/g, '')
  ) || null;
}

// Helper: get full history for a vehicle
export function getVehicleHistory(vehicleId) {
  return {
    ownership: mockOwnershipHistory.filter(r => r.vehicleId === vehicleId),
    service: mockServiceRecords.filter(r => r.vehicleId === vehicleId),
    mileage: mockMileageHistory.filter(r => r.vehicleId === vehicleId),
    accidents: mockAccidentRecords.filter(r => r.vehicleId === vehicleId),
  };
}
